// Generates test/golden.h: points with the ids of the IEEE-754 reference (ieee.h).
// Not part of the build; run it once to refresh the table:
//
//   c++ -std=c++20 -O1 -I. -I<cartesian dir> test/gen_golden.cc htm.cc constraint.cc \
//       <cartesian dir>/cartesian.cc -o gen_golden && ./gen_golden > test/golden.h
//
// Run it on a build whose Cartesian operators fuse (clang on arm64, GCC with -mfma):
// the last class is the random points on which the frozen Cartesian-object walk and
// the IEEE reference disagree, the points a contracting getId would get wrong.
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <random>
#include <vector>

#include "../test/frozen.h"
#include "../test/ieee.h"

struct Entry {
	double x, y, z;
	uint64_t id;
};

static std::vector<Entry> entries;

static void add(double x, double y, double z) {
	Cartesian c(x, y, z);
	entries.push_back({x, y, z, ieee::getId(c)});
}

static void add_normalized(double x, double y, double z) {
	double n = std::sqrt(x * x + y * y + z * z);
	add(x / n, y / n, z / n);
}

int main() {
	std::mt19937_64 rng(20261031);
	std::normal_distribution<double> g(0, 1);

	// Poles, axes, diagonals and signed zeros.
	const double axes[] = {0.0, -0.0, 1.0, -1.0};
	for (double x : axes) for (double y : axes) for (double z : axes) {
		if (x != 0.0 || y != 0.0 || z != 0.0) add(x, y, z);
	}
	add_normalized(1, 1, 1);
	add_normalized(-1, 1, -1);
	add_normalized(1, -1, 0);
	add_normalized(0, 1, -1);

	// Random points on the sphere.
	for (int i = 0; i < 96; ++i) {
		add_normalized(g(rng), g(rng), g(rng));
	}

	// Trixel vertices and edge midpoints at random levels, exact and one ulp off in each coordinate.
	for (int i = 0; i < 24; ++i) {
		const auto& t = start_trixels[rng() % 8];
		ieee::V v0{start_vertices[t.v0].x, start_vertices[t.v0].y, start_vertices[t.v0].z};
		ieee::V v1{start_vertices[t.v1].x, start_vertices[t.v1].y, start_vertices[t.v1].z};
		ieee::V v2{start_vertices[t.v2].x, start_vertices[t.v2].y, start_vertices[t.v2].z};
		int lvl = rng() % 25;
		for (int d = 0; d < lvl; ++d) {
			ieee::V w2 = ieee::mid(v0, v1), w0 = ieee::mid(v1, v2), w1 = ieee::mid(v2, v0);
			switch (rng() % 4) {
				case 0: v1 = w2; v2 = w1; break;
				case 1: v0 = v1; v1 = w0; v2 = w2; break;
				case 2: v0 = v2; v1 = w1; v2 = w0; break;
				default: v0 = w0; v1 = w1; v2 = w2; break;
			}
		}
		ieee::V m = ieee::mid(v0, v1);
		for (const auto& q : {v0, m}) {
			add(q.x, q.y, q.z);
			add(std::nextafter(q.x, 2.0), q.y, q.z);
			add(q.x, std::nextafter(q.y, -2.0), q.z);
		}
	}

	// Random points on which the frozen walk (the build's own Cartesian operators)
	// and the IEEE reference disagree.
	size_t found = 0;
	const size_t wanted = 96;
	for (size_t i = 0; i < 20000000 && found < wanted; ++i) {
		double x = g(rng), y = g(rng), z = g(rng);
		double n = std::sqrt(x * x + y * y + z * z);
		Cartesian c(x / n, y / n, z / n);
		uint64_t o = ieee::getId(c);
		if (frozen_getId(c) != o) {
			entries.push_back({c.x, c.y, c.z, o});
			++found;
		}
	}
	if (found < wanted) {
		std::fprintf(stderr, "only %zu contraction-sensitive points: run on a build that fuses\n", found);
	}

	std::printf("// Generated by test/gen_golden.cc: points and the ids of the IEEE-754 reference (ieee.h).\n");
	std::printf("// Coordinates are exact hexadecimal floating-point literals.\n");
	std::printf("#pragma once\n\n#include <cstdint>\n\n");
	std::printf("struct golden_t {\n\tdouble x, y, z;\n\tuint64_t id;\n};\n\n");
	std::printf("static const golden_t golden_ids[] = {\n");
	for (const auto& e : entries) {
		std::printf("\t{%a, %a, %a, %lluULL},\n", e.x, e.y, e.z, (unsigned long long)e.id);
	}
	std::printf("};\n");
	return 0;
}
