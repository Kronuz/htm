// Differential test of HTM::getId / getTrixelName.
//
// The contract: HTM::getId returns the id of plain IEEE-754 double arithmetic,
// whatever the compiler's contraction mode (ieee.h is that reference: every
// operation rounded on its own). It is checked against ieee.h on every input,
// against the golden ids in golden.h, and against the Cartesian-object walk in
// frozen.h. That walk runs through the operators in cartesian.cc, so it returns
// the same ids only where the build rounds each operation on its own. Where the
// build fuses (clang on FMA hardware, GCC on arm64 or with -mfma) the two walks
// differ for points within rounding of a trixel edge: on random points only in the
// deepest levels, on edge points anywhere. The test then counts the differences
// and holds random points to the same first 16 levels.
//
// Inputs are random points on the sphere plus the cases that decide ties: poles,
// axis planes, signed zeros, start-trixel edges, and exact trixel
// vertices/midpoints at many levels.
//
// Usage: htm_diff_test [random_points]   (default 200,000)
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <random>
#include <string>
#include <vector>

#include "frozen.h"
#include "golden.h"
#include "htm.h"
#include "ieee.h"

static size_t checked = 0, failures = 0, fused_diffs = 0;
static bool frozen_exact = true;

// Whether the Cartesian operators (cartesian.cc) round every operation on their
// own on this build: norm(), * and ^ against the same expressions in ieee.h.
static bool cartesian_is_ieee() {
	std::mt19937_64 rng(777);
	std::normal_distribution<double> g(0, 1);
	using ieee::r;
	for (int i = 0; i < 20000; ++i) {
		Cartesian a(g(rng), g(rng), g(rng)), b(g(rng), g(rng), g(rng));
		if (a.norm() != r(std::sqrt(r(r(r(a.x * a.x) + r(a.y * a.y)) + r(a.z * a.z))))) return false;
		if ((a ^ b).x != r(r(a.y * b.z) - r(b.y * a.z))) return false;
		if (a * b != r(r(r(a.x * b.x) + r(a.y * b.y)) + r(a.z * b.z))) return false;
	}
	return true;
}

static void check(double x, double y, double z, bool names, bool random = false) {
	Cartesian c(x, y, z);
	++checked;
	uint64_t a = frozen_getId(c), b = HTM::getId(c), o = ieee::getId(c);
	bool bad = b != o;
	if (bad && ++failures <= 10) {
		std::printf("IEEE MISMATCH (%.17g %.17g %.17g): %llu vs %llu\n", x, y, z,
			(unsigned long long)o, (unsigned long long)b);
	}
	if (a != b) {
		// The frozen walk and the new one differ only where its Cartesian operators fuse.
		if (frozen_exact || (random && (a >> 18) != (b >> 18))) {
			bad = true;
			if (++failures <= 10) {
				std::printf("MISMATCH (%.17g %.17g %.17g): %llu vs %llu\n", x, y, z,
					(unsigned long long)a, (unsigned long long)b);
			}
		} else {
			++fused_diffs;
		}
	}
	if (names) {
		std::string name = a == b ? frozen_getTrixelName(c) : frozen_name_from_id(b);
		if (name != HTM::getTrixelName(c) && ++failures <= 10) {
			std::printf("NAME MISMATCH (%.17g %.17g %.17g)\n", x, y, z);
		}
	}
}

static void check_normalized(double x, double y, double z, bool names, bool random = false) {
	double n = std::sqrt(x * x + y * y + z * z);
	if (n > 0) check(x / n, y / n, z / n, names, random);
}

int main(int argc, char** argv) {
	size_t n = argc > 1 ? std::strtoull(argv[1], nullptr, 10) : 200000;
	frozen_exact = cartesian_is_ieee();
	std::mt19937_64 rng(12345);
	std::normal_distribution<double> g(0, 1);
	std::uniform_real_distribution<double> u(-1, 1);

	// The golden ids: points from every class, ids from ieee.h (the IEEE-754
	// reference) when the table was generated by gen_golden.cc.
	size_t golden_failures = 0;
	for (const auto& e : golden_ids) {
		++checked;
		uint64_t id = HTM::getId(Cartesian(e.x, e.y, e.z));
		if (id != e.id) {
			++golden_failures;
			if (++failures <= 10) {
				std::printf("GOLDEN MISMATCH (%a %a %a): %llu vs %llu\n", e.x, e.y, e.z,
					(unsigned long long)e.id, (unsigned long long)id);
			}
		}
	}
	std::printf("golden ids: %zu points, %zu mismatches\n", sizeof golden_ids / sizeof *golden_ids, golden_failures);

	// Signed zeros, poles, axes, diagonals, and tiny components.
	const double vals[] = {0.0, -0.0, 1.0, -1.0, 0.5, -0.5, 1e-300, -1e-300, 1e-16, -1e-16, 0.7071067811865476, -0.7071067811865476};
	for (double x : vals) for (double y : vals) for (double z : vals) {
		check(x, y, z, true);
		check_normalized(x, y, z, true);
	}

	// Gaussian normalized (uniform on the sphere), and unnormalized, and a
	// cube-uniform (non-normalized) sample.
	for (size_t i = 0; i < n; ++i) {
		double x = g(rng), y = g(rng), z = g(rng);
		bool names = (i % 8) == 0;
		check_normalized(x, y, z, names, true);
		if ((i & 7) == 1) check(u(rng), u(rng), u(rng), names, true);
	}

	// Points on the start-trixel great-circle boundaries (an axis plane) and
	// on the edges of deeper trixels: a vertex or midpoint at each level, plus
	// slight perturbations of each.
	for (size_t i = 0; i < n / 8; ++i) {
		double a = g(rng), b = g(rng);
		int plane = i % 3;
		double p[3] = {a, b, 0};
		if (plane == 1) { p[2] = p[1]; p[1] = 0; }
		if (plane == 2) { p[2] = p[0]; p[0] = 0; }
		check_normalized(p[0], p[1], p[2], (i & 15) == 0);
	}
	std::uniform_int_distribution<int> pick(0, 7);
	for (size_t i = 0; i < n / 8; ++i) {
		const auto& t = start_trixels[pick(rng)];
		Cartesian v0 = start_vertices[t.v0], v1 = start_vertices[t.v1], v2 = start_vertices[t.v2];
		int lvl = std::uniform_int_distribution<int>(0, 24)(rng);
		for (int d = 0; d < lvl; ++d) {
			auto w2 = frozen_mid(v0, v1), w0 = frozen_mid(v1, v2), w1 = frozen_mid(v2, v0);
			switch (std::uniform_int_distribution<int>(0, 3)(rng)) {
				case 0: v1 = w2; v2 = w1; break;
				case 1: v0 = v1; v1 = w0; v2 = w2; break;
				case 2: v0 = v2; v1 = w1; v2 = w0; break;
				default: v0 = w0; v1 = w1; v2 = w2; break;
			}
		}
		auto m01 = frozen_mid(v0, v1), m12 = frozen_mid(v1, v2);
		const Cartesian pts[] = {v0, v1, v2, m01, m12};
		for (const auto& q : pts) {
			check(q.x, q.y, q.z, true);
			check_normalized(q.x + 1e-12 * g(rng), q.y + 1e-12 * g(rng), q.z + 1e-12 * g(rng), false);
		}
		// A point on the edge v0-v1 (a great-circle arc).
		double t01 = std::uniform_real_distribution<double>(0, 1)(rng);
		check_normalized(v0.x * (1 - t01) + v1.x * t01, v0.y * (1 - t01) + v1.y * t01, v0.z * (1 - t01) + v1.z * t01, false);
	}

	// getTrixelName(id): every start id, ids from the sampled points, and the
	// extremes of the valid range.
	for (uint64_t id = 8; id < 16; ++id) {
		if (frozen_name_from_id(id) != HTM::getTrixelName(id)) ++failures;
	}
	for (size_t i = 0; i < n; ++i) {
		int lvl = std::uniform_int_distribution<int>(0, 25)(rng);
		uint64_t id = (8 + (rng() & 7)) << (2 * lvl);
		id |= rng() & ((uint64_t(1) << (2 * lvl)) - 1);
		++checked;
		if (frozen_name_from_id(id) != HTM::getTrixelName(id) && ++failures <= 10) {
			std::printf("NAME MISMATCH %llu\n", (unsigned long long)id);
		}
	}

	std::printf("checked %zu, failures %zu%s", checked, failures, frozen_exact ? "\n" : "");
	if (!frozen_exact) {
		std::printf(" (the Cartesian operators fuse on this build: the frozen walk differs on %zu points)\n", fused_diffs);
	}
	return failures ? 1 : 0;
}
